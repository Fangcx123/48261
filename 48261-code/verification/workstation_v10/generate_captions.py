"""Regenerate v2 captions and 16x16 Chinese glyph ROM.
Timings follow phrase boundaries aligned from the verified v1 recording.
"""
from pathlib import Path
import json, wave, hashlib
from PIL import Image, ImageDraw, ImageFont

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/'doc/工位四步通_指导语音_v2'
WAV=OUT/'AUDIO.WAV'
segments=[
 (0.00,2.50,'欢迎使用工位四步通。'),
 (2.97,5.67,'四张图卡分别介绍准备、'),
 (5.67,6.60,'操作、'),
 (6.60,7.40,'对照、'),
 (7.40,8.20,'和收尾。'),
 (8.20,9.94,'开始操作前，'),
 (9.94,12.12,'请确认安全事项，'),
 (12.12,14.5045,'并遵循教师指导。'),
]
with wave.open(str(WAV)) as f:
 assert (f.getframerate(),f.getsampwidth(),f.getnchannels())==(48000,2,1)
 duration=f.getnframes()/f.getframerate()
frame_rate=48000
if abs(segments[-1][1]-duration)>1/frame_rate:
 raise SystemExit(f'caption timeline ends at {segments[-1][1]:.6f}s, WAV is {duration:.6f}s')
if any(a<0 or b<=a or b>duration+1/frame_rate for a,b,_ in segments):
 raise SystemExit('caption cue falls outside the WAV duration')
cues=[dict(start_sample=round(a*frame_rate),end_sample=round(b*frame_rate),text=t) for a,b,t in segments]
manifest=dict(wav_sha256=hashlib.sha256(WAV.read_bytes()).hexdigest(),sample_rate=48000,
             duration_seconds=duration,
             timing_method='aligned to the corresponding phrases in the verified v1 recording',cues=cues)
(OUT/'图片切换样本点.json').write_text(json.dumps({
 'sample_rate':48000,
 'events':[{'sample':0,'image':0,'keyword':'语音开始'},
           {'sample':round(5.67*48000),'image':1,'keyword':'操作'},
           {'sample':round(6.60*48000),'image':2,'keyword':'对照'},
           {'sample':round(7.40*48000),'image':3,'keyword':'收尾'}]},ensure_ascii=False,indent=2),encoding='utf-8')
(OUT/'字幕时间表.json').write_text(json.dumps(manifest,ensure_ascii=False,indent=2),encoding='utf-8')
def stamp(s):
 n=round(s*1000);return f'{n//3600000:02}:{n//60000%60:02}:{n//1000%60:02},{n%1000:03}'
(OUT/'字幕.srt').write_text('\n'.join(f'{i+1}\n{stamp(a)} --> {stamp(b)}\n{t}\n' for i,(a,b,t) in enumerate(segments)),encoding='utf-8')
chars=[' ']+sorted(set(''.join(t for _,_,t in segments)))
ids={c:i for i,c in enumerate(chars)}
font=ImageFont.truetype('C:/Windows/Fonts/simhei.ttf',16)
glyphs=[]
for c in chars:
 im=Image.new('1',(16,16));d=ImageDraw.Draw(im);d.text((0,-1),c,font=font,fill=1)
 glyphs.extend(sum((1<<(15-x)) for x in range(16) if im.getpixel((x,y))) for y in range(16))
rom=['// Generated by verification/workstation_v10/generate_captions.py.','module speech_caption_rom(',
 ' input clk,input [9:0] text_addr,input [3:0] glyph_row,output reg [15:0] row_bits',');',
 f' reg [6:0] text_mem[0:1023];reg [15:0] glyph_mem[0:{len(glyphs)-1}];',
 ' reg [6:0] char_id;reg [3:0] row_q;integer i;',' initial begin',
 '  for(i=0;i<1024;i=i+1) text_mem[i]=0;']
for n,(_,_,t) in enumerate(segments):
 for j,c in enumerate(t):rom.append(f"  text_mem[{n*32+j}]=7'd{ids[c]};")
for n,g in enumerate(glyphs):rom.append(f"  glyph_mem[{n}]=16'h{g:04x};")
rom+=[' end',' always @(posedge clk) begin','  char_id<=text_mem[text_addr];row_q<=glyph_row;',
 '  row_bits<=glyph_mem[{char_id,row_q}];',' end','endmodule']
HDL=ROOT/'src/user_source/hdl_source/display'
(HDL/'speech_caption_rom.v').write_text('\n'.join(rom)+'\n',encoding='utf-8')
table=['// Generated caption sample boundaries, 48kHz.',' always @* begin','  cue_start=0;cue_end=0;cue_length=0;','  case(cue)']
for n,c in enumerate(cues):table.append(f"   {n}:begin cue_start=32'd{c['start_sample']};cue_end=32'd{c['end_sample']};cue_length=6'd{len(c['text'])};end")
table+=['   default:;','  endcase',' end']
(HDL/'speech_caption_timing.vh').write_text('\n'.join(table)+'\n',encoding='utf-8')
with (HDL/'speech_caption_rom.v').open('a',encoding='utf-8') as f:
 f.write('module speech_caption_timing(input [4:0] cue,output reg [31:0] cue_start,cue_end,output reg [5:0] cue_length);\n')
 f.write('\n'.join(table)+'\nendmodule\n')
# Review artifact uses the same raster glyphs that hardware displays, at 2x.
proof=Image.new('RGB',(640,48*len(cues)),(16,16,24))
for n,c in enumerate(cues):
 for j,ch in enumerate(c['text']):
  g=Image.new('RGB',(16,16));p=g.load()
  for y in range(16):
   for x in range(16):p[x,y]=(255,255,255) if glyphs[ids[ch]*16+y]&(1<<(15-x)) else (16,16,24)
  proof.paste(g.resize((32,32),Image.Resampling.NEAREST),(16+j*32,n*48+8))
proof.save(OUT/'字幕字模校样.png')
print(f'Generated {len(cues)} cues, {len(chars)} glyphs, {len(glyphs)*2} glyph bytes')
